function getPreset(id) {
  return PRESETS[String(id || "").trim()] || null;
}

function listPresets() {
  return Object.entries(PRESETS).map(([id, preset]) => ({
    id,
    label: preset.label,
    section: preset.section,
    lang: preset.lang,
    favorites: preset.favorites.length,
  }));
}

